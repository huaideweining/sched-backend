-- 方案③ 调度后端 DDL（Oracle 19c，用户 jddba）
-- 注意：MODE 为 Oracle 保留字，必须加双引号；其余标识符保持大写。
-- 执行：sqlplus jddba/<pwd>@//172.16.253.180:1521/orcl @sched_ddl.sql

WHENEVER SQLERROR CONTINUE;

CREATE TABLE SCHED_TASK (
  TASK_ID      NUMBER(19)    NOT NULL,
  USER_ID      VARCHAR2(64)  NOT NULL,
  NAME         VARCHAR2(200) NOT NULL,
  CONTENT      VARCHAR2(1000),
  "MODE"       VARCHAR2(16)  NOT NULL,
  INTERVAL_MIN NUMBER(10),
  AT_TIME      VARCHAR2(8),
  WEEKDAY      NUMBER(1),
  MONTH_DAY    NUMBER(2),
  PRIORITY     NUMBER(3),
  PROJECT      VARCHAR2(200),
  TIMEZONE     VARCHAR2(64) DEFAULT 'Asia/Shanghai' NOT NULL,
  ENABLED      CHAR(1)      DEFAULT 'Y' NOT NULL,
  VERSION      NUMBER(10)   DEFAULT 0 NOT NULL,
  CREATED_AT   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SCHED_TASK PRIMARY KEY (TASK_ID),
  CONSTRAINT UK_TASK_USER_NAME UNIQUE (USER_ID, NAME),
  CONSTRAINT CK_TASK_MODE CHECK ("MODE" IN ('INTERVAL','DAILY','WEEKLY','MONTHLY')),
  CONSTRAINT CK_TASK_ENABLED CHECK (ENABLED IN ('Y','N'))
);
CREATE INDEX IDX_TASK_USER ON SCHED_TASK(USER_ID, ENABLED);

CREATE TABLE SCHED_TRIGGER (
  TRIGGER_ID     NUMBER(19)    NOT NULL,
  TASK_ID        NUMBER(19)    NOT NULL,
  USER_ID        VARCHAR2(64)  NOT NULL,
  PREV_FIRE_TIME TIMESTAMP(6),
  NEXT_FIRE_TIME TIMESTAMP(6)  NOT NULL,
  STATUS         VARCHAR2(16)  NOT NULL,
  VERSION        NUMBER(10)    DEFAULT 0 NOT NULL,
  UPDATED_AT     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SCHED_TRIGGER PRIMARY KEY (TRIGGER_ID),
  CONSTRAINT FK_TRIGGER_TASK FOREIGN KEY (TASK_ID) REFERENCES SCHED_TASK(TASK_ID),
  CONSTRAINT CK_TRIGGER_STATUS CHECK (STATUS IN ('WAITING','ACQUIRED','COMPLETED','PAUSED','ERROR'))
);
CREATE INDEX IDX_TRIGGER_DUE ON SCHED_TRIGGER(STATUS, NEXT_FIRE_TIME);
CREATE INDEX IDX_TRIGGER_TASK ON SCHED_TRIGGER(TASK_ID);

CREATE TABLE SCHED_FIRE_LOG (
  FIRE_ID            NUMBER(19)    NOT NULL,
  TASK_ID            NUMBER(19)    NOT NULL,
  TRIGGER_ID         NUMBER(19)    NOT NULL,
  USER_ID            VARCHAR2(64)  NOT NULL,
  SCHEDULED_FIRE_TIME TIMESTAMP(6) NOT NULL,
  ACTUAL_FIRE_TIME   TIMESTAMP(6),
  STATUS             VARCHAR2(16)  NOT NULL,
  TODO_ID            NUMBER(19),
  RETRY_COUNT        NUMBER(3)    DEFAULT 0,
  ERROR_MSG          VARCHAR2(2000),
  CONSTRAINT PK_SCHED_FIRE_LOG PRIMARY KEY (FIRE_ID),
  CONSTRAINT UK_FIRE_TASK_TIME UNIQUE (TASK_ID, SCHEDULED_FIRE_TIME),
  CONSTRAINT CK_FIRE_STATUS CHECK (STATUS IN ('SUCCESS','FAILED'))
);
CREATE INDEX IDX_FIRE_TASK ON SCHED_FIRE_LOG(TASK_ID, SCHEDULED_FIRE_TIME);

CREATE TABLE SCHED_TODO (
  TODO_ID           NUMBER(19)    NOT NULL,
  USER_ID           VARCHAR2(64)  NOT NULL,
  TITLE             VARCHAR2(1000) NOT NULL,
  PRIORITY          NUMBER(3),
  DUE_DATE          DATE,
  DONE              CHAR(1)       DEFAULT 'N' NOT NULL,
  PROJECT           VARCHAR2(200),
  SOURCE_TASK_ID    NUMBER(19),
  SCHEDULED_FIRE_TIME TIMESTAMP(6),
  CREATED_DATE      DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_SCHED_TODO PRIMARY KEY (TODO_ID),
  CONSTRAINT CK_TODO_DONE CHECK (DONE IN ('Y','N'))
);
CREATE INDEX IDX_TODO_USER ON SCHED_TODO(USER_ID, DONE);
CREATE INDEX IDX_TODO_SRC  ON SCHED_TODO(SOURCE_TASK_ID);

CREATE TABLE SCHED_NODE (
  NODE_ID        VARCHAR2(64)  NOT NULL,
  HOST           VARCHAR2(128),
  PORT           NUMBER(6),
  IS_LEADER      CHAR(1)       DEFAULT 'N',
  SHARD_MOD      NUMBER(3),
  SHARD_TOTAL    NUMBER(3),
  LAST_HEARTBEAT TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  STATUS         VARCHAR2(16)  DEFAULT 'UP',
  CONSTRAINT PK_SCHED_NODE PRIMARY KEY (NODE_ID)
);

CREATE TABLE SCHED_USER (
  USER_ID    VARCHAR2(64)  NOT NULL,
  USERNAME   VARCHAR2(128) NOT NULL,
  PASSWORD   VARCHAR2(128) NOT NULL,
  STATUS     CHAR(1)       DEFAULT 'Y' NOT NULL,
  CREATED_AT TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SCHED_USER PRIMARY KEY (USER_ID),
  CONSTRAINT UK_SCHED_USER_NAME UNIQUE (USERNAME),
  CONSTRAINT CK_SCHED_USER_STATUS CHECK (STATUS IN ('Y','N'))
);
CREATE INDEX IDX_USER_NAME ON SCHED_USER(USERNAME);

CREATE SEQUENCE SEQ_SCHED_TASK     START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_SCHED_TRIGGER  START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_SCHED_FIRE_LOG START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE SEQ_SCHED_TODO     START WITH 1 INCREMENT BY 1;

COMMIT;
EXIT;
