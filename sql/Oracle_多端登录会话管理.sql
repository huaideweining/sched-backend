-- ==================================================================================================
-- 二、索引：每一个索引都对应一条明确的查询/维护 SQL
-- ==================================================================================================

-- 1) 会话号唯一索引
--    作用：按 sessionId 精确查会话（续期、踢下线、校验），保证同一个业务会话号全局唯一。
--    【Oracle 关键差异】Oracle 的唯一索引允许出现多个 NULL（MySQL 的 UNIQUE 也允许，但
--    语义细节不同；而 SQL Server 的 UNIQUE 不允许 NULL）。若 SESSION_ID 可为 NULL，
--    所有 NULL 行都会被允许重复插入，"唯一"形同虚设。因此此处显式 NOT NULL + 独立唯一索引，
--    这是 Oracle 与 MySQL 在唯一约束上最容易踩的坑。
CREATE UNIQUE INDEX UK_SYS_USER_SESSION_SESSION_ID ON SYS_USER_SESSION (SESSION_ID);

-- 2) 用户 + 状态 组合索引（最左前缀 USER_ID）
--    作用：支撑两条高频 SQL：
--      a) "该用户当前在线终端列表"（WHERE USER_ID=? AND STATUS='ACTIVE' AND EXPIRE_TIME>?）
--      b) "该用户活跃会话数"（判断是否超过最大会话数）
--    为什么是组合而不是单列 USER_ID：STATUS 只有 4 个取值，区分度低；把高区分度的 USER_ID 放前面，
--    可以让索引直接定位到用户的全部行，再在索引内过滤 STATUS/EXPIRE_TIME，无需回表（配合下面索引即可覆盖）。
CREATE INDEX IDX_SYS_USER_SESSION_USER_STATUS ON SYS_USER_SESSION (USER_ID, STATUS);

-- 3) 过期时间单列索引
--    作用：支撑过期清理任务 "WHERE STATUS='ACTIVE' AND EXPIRE_TIME <= SYSTIMESTAMP" 的顺序扫描。
--    没有它，清理任务每次都是全表扫描；有它，可以走索引范围扫描并配合 ROWNUM 分批。
CREATE INDEX IDX_SYS_USER_SESSION_EXPIRE_TIME ON SYS_USER_SESSION (EXPIRE_TIME);

-- 4) 活跃时间单列索引
--    作用：a) 滑动续期按 LAST_ACTIVE_TIME 降序取"最近活跃"；
--          b) 超出最大会话数时按 LAST_ACTIVE_TIME 升序淘汰"最旧"的会话。
CREATE INDEX IDX_SYS_USER_SESSION_LAST_ACTIVE ON SYS_USER_SESSION (LAST_ACTIVE_TIME);

-- 5) 组合覆盖索引（可选，推荐生产环境开启）
--    作用：把第 2、4 条 SQL 所需的列都放进索引，避免回表，在线终端列表与淘汰查询都是纯索引扫描。
CREATE INDEX IDX_SYS_USER_SESSION_USER_ACTIVE ON SYS_USER_SESSION (USER_ID, STATUS, LAST_ACTIVE_TIME);

-- 6) 令牌哈希索引（可选但建议）
--    作用：校验请求按哈希等值查询（WHERE TOKEN_HASH=?）。哈希是定长十六进制串，区分度接近 1，
--    建索引后可避免每次校验都扫全表。用普通索引而非唯一索引：同一哈希重复出现说明盐或令牌生成有问题，
--    不应当成业务错误，交给监控告警更合适。
CREATE INDEX IDX_SYS_USER_SESSION_TOKEN_HASH ON SYS_USER_SESSION (TOKEN_HASH);

-- ==================================================================================================
-- 三、约束：NOT NULL / 主键 / 唯一 / CHECK
-- ==================================================================================================
-- Oracle 不支持 MySQL 那样的 CHECK 内联写法时可用 ALTER 追加；Oracle 12c 起 CHECK 也可以内联，
-- 这里统一用 ALTER 写出，方便按环境裁剪。注意：Oracle 的 CHECK 约束对已有的非法数据不会自动纠正，
-- 建约束前请先跑下面的"数据体检"段（历史数据一般为 NULL/空，不会违反 CHECK）。

ALTER TABLE SYS_USER_SESSION ADD CONSTRAINT CK_SYS_USER_SESSION_STATUS
    CHECK (STATUS IN ('ACTIVE', 'EXPIRED', 'LOGOUT', 'KICKED'));

ALTER TABLE SYS_USER_SESSION ADD CONSTRAINT CK_SYS_USER_SESSION_DEVICE
    CHECK (DEVICE_TYPE IN ('PC', 'MOBILE', 'TABLET', 'MINI_PROGRAM', 'OTHER'));

-- 时间边界自洽：过期时间必须在登录之后。防止程序传参写反导致"永不过期"的僵尸会话。
ALTER TABLE SYS_USER_SESSION ADD CONSTRAINT CK_SYS_USER_SESSION_TIME
    CHECK (EXPIRE_TIME >= LOGIN_TIME);

-- 终态字段与状态保持一致（仅约束语义，不强制非空，便于历史兼容）
ALTER TABLE SYS_USER_SESSION ADD CONSTRAINT CK_SYS_USER_SESSION_TERMINAL
    CHECK ((STATUS = 'ACTIVE' AND LOGOUT_TIME IS NULL)
        OR (STATUS <> 'ACTIVE' AND LOGOUT_TIME IS NOT NULL));

-- 会话号非空是唯一索引生效的前置条件（见索引 1 的说明）
ALTER TABLE SYS_USER_SESSION MODIFY (SESSION_ID VARCHAR2(64) NOT NULL);

