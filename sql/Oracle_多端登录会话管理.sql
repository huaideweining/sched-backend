-- ==================================================================================================
-- 五、清理过期会话（可选段）
--    推荐：用 Java 侧 @Scheduled（见 SessionCleanupTask，默认 10 分钟一次）或下面的 Oracle 存储过程；
--    两者选其一，不要重复跑。STORED PROCEDURE 的优势是可以在数据库侧用 DBMS_SCHEDULER 托管。
-- ==================================================================================================
CREATE OR REPLACE PROCEDURE PRG_CLEAN_EXPIRE_SESSION
(
    P_BATCH_SIZE  IN  NUMBER DEFAULT 1000,   -- 单批处理的行数上限，避免长事务
    P_TOTAL       IN OUT NUMBER             -- 累计清理行数
)
IS
    n_rows NUMBER := 0;
BEGIN
    IF P_TOTAL IS NULL THEN
        P_TOTAL := 0;
    END IF;

    LOOP
        -- 先改逻辑状态，不动物理行；ROWNUM 限制单批规模，避免锁表时间过长
        UPDATE SYS_USER_SESSION S
           SET S.STATUS      = 'EXPIRED',
               S.LOGOUT_TYPE = 'EXPIRED',
               S.LOGOUT_TIME = SYSTIMESTAMP,
               S.UPDATE_TIME = SYSTIMESTAMP
         WHERE S.STATUS = 'ACTIVE'
           AND S.EXPIRE_TIME <= SYSTIMESTAMP
           AND ROWNUM <= P_BATCH_SIZE;

        n_rows := SQL%ROWCOUNT;
        P_TOTAL := P_TOTAL + n_rows;
        EXIT WHEN n_rows = 0;   -- 没有更多过期行就退出，避免在锁内空转
    END LOOP;

    COMMIT;
END PRG_CLEAN_EXPIRE_SESSION;
/

-- 调用方式（返回清理了多少行）：
--   DECLARE v NUMBER; BEGIN PRG_CLEAN_EXPIRE_SESSION(1000, v); DBMS_OUTPUT.PUT_LINE('cleared=' || v); END;
-- 直接用 SQL 版（不想建存储过程时）：
--   UPDATE SYS_USER_SESSION SET STATUS='EXPIRED', LOGOUT_TYPE='EXPIRED', LOGOUT_TIME=SYSTIMESTAMP
--    WHERE STATUS='ACTIVE' AND EXPIRE_TIME <= SYSTIMESTAMP AND ROWNUM <= 1000;

-- 可选的 Oracle 定时作业（10 分钟一次）。生产环境若已用 Java 定时任务，请注释掉这段。
BEGIN
    DBMS_SCHEDULER.CREATE_JOB (
        job_name        => 'JOB_CLEAN_EXPIRE_SESSION',
        job_type        => 'STORED_PROCEDURE',
        job_action      => 'PRG_CLEAN_EXPIRE_SESSION',
        number_of_args  => 2,
        start_date      => SYSTIMESTAMP,
        repeat_interval => 'FREQ=MINUTELY; INTERVAL=10',
        end_date        => NULL,
        enabled         => FALSE,
        comments        => '清理 SYS_USER_SESSION 中已过期的会话（默认关闭，需显式 ENABLE）'
    );
    DBMS_SCHEDULER.SET_JOB_ARGUMENT_VALUE('JOB_CLEAN_EXPIRE_SESSION', 1, 1000);
    DBMS_SCHEDULER.SET_JOB_ARGUMENT_VALUE('JOB_CLEAN_EXPIRE_SESSION', 2, 0);
END;
/

