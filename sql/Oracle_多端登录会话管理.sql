-- ==================================================================================================
-- 六、MyBatis-Plus 的 Oracle 分页（PaginationInnerInterceptor + DbType.ORACLE）说明
-- ==================================================================================================
-- 1) 只需在配置里声明 DbType.ORACLE，拦截器会自动拼分页 SQL，业务代码与写 MySQL 完全一致：
--      Page<SysUserSession> page = new Page<>(current, size);
--      mapper.selectPage(page, wrapper);   // 无需手写 LIMIT / ROWNUM
--
-- 2) Oracle 方言必须使用"嵌套子查询 + ROWNUM"，MyBatis-Plus 实际生成的形式如下：
--      SELECT * FROM (
--          SELECT TMP.*, ROWNUM AS RN FROM (
--              SELECT ... FROM SYS_USER_SESSION WHERE USER_ID = ? ORDER BY LAST_ACTIVE_TIME DESC
--          ) TMP
--          WHERE ROWNUM <= ?
--      ) WHERE RN > ?
--
-- 3) 为什么必须套三层、且 ORDER BY 只能写在最内层：
--    - ROWNUM 是"结果集生成过程中的行号"，在排序完成之前就已分配；
--      如果把 ROWNUM <= ? 写在带 ORDER BY 的同一层，Oracle 会先取前 N 行再排序，翻页结果就是错的。
--    - 因此：最内层做"过滤 + 排序"，中间层用 ROWNUM 限定上限，最外层用别名 RN 取下限，实现页码偏移。
--
-- 4) 注意点：
--    - ORDER BY 必须写在选择列表里出现过的列上（CLOB 列不建议参与排序，USER_AGENT 不要进 ORDER BY）；
--    - setMaxLimit(1000) 防止 pageSize 被传得过大；setOverflow(true) 让超页码返回空页而不是报错；
--    - 排序字段为 NULL 时 Oracle 默认 NULLS LAST，若业务要求 NULL 排最前需显式 NULLS FIRST/LAST。

-- ==================================================================================================
-- 七、11g 兼容说明（若生产是 Oracle 11g，请做以下替换）
-- ==================================================================================================
