-- ==================================================================================================
-- 一、核心表：SYS_USER_SESSION（多端登录会话表）
-- ==================================================================================================
CREATE TABLE SYS_USER_SESSION
(
    -- 主键：Oracle 12c 起支持 IDENTITY 列，无需再维护 序列 + 触发器（11g 见文末说明）
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY   NOT NULL,

    -- 业务主键：会话号。对外暴露给前端（用于查在线终端、踢下线），与主键 ID 解耦，
    -- 这样后续换主键策略（如分库分片）不影响已签发的令牌。
    -- 【长度校准】代码 TokenServiceImpl.generateSessionId() 产出 "sess_"+64位hex=69 字符，
    -- 曾按 64 建列导致登录 INSERT ORA-12899（在旧库被缺表 ORA-942 掩盖未暴露），现放宽到 128。
    SESSION_ID          VARCHAR2(128) NOT NULL,

    -- 归属用户：业务侧用户主键。ERP 场景建议存 user_id，而不是登录名，改名后会话不失效。
    USER_ID             VARCHAR2(64)  NOT NULL,

    -- 冗余登录名，仅用于列表展示/审计，避免每次关联用户表
    USERNAME            VARCHAR2(64),
    DISPLAY_NAME        VARCHAR2(128),

    -- 【安全硬要求】只保存 SHA-256(服务端盐 + 明文 token) 的十六进制串，
    -- DBA 或拖库者拿到此列无法还原明文 token，日志里也禁止打印明文。
    TOKEN_HASH          VARCHAR2(128) NOT NULL,

    -- 终端类型：PC / MOBILE / TABLET / MINI_PROGRAM / OTHER，用于"同设备踢下线"与列表分组
    DEVICE_TYPE         VARCHAR2(32)  NOT NULL,

    -- 终端指纹（设备 ID / 机器码）：防止令牌被复制到另一台电脑使用
    DEVICE_ID           VARCHAR2(128),
    DEVICE_INFO         VARCHAR2(500),   -- 浏览器/操作系统描述，超长或有中文，用 VARCHAR2 可满足

    -- 网络与来源
    IP                  VARCHAR2(64),
    USER_AGENT          CLOB,            -- User-Agent 长度不可控，用 CLOB；MyBatis 直接映射为 String

    -- 时间三元组：LOGIN_TIME 起点 / LAST_ACTIVE_TIME 上次确认活跃 / EXPIRE_TIME 绝对边界
    -- Oracle 的 DATE 只有秒级精度且无时区概念，时间字段统一用 TIMESTAMP(6)（毫秒 + 纳秒）
    LOGIN_TIME          TIMESTAMP(6)  NOT NULL,   -- 会话创建时刻，也是"总生命周期"起算点
    LAST_ACTIVE_TIME    TIMESTAMP(6)  NOT NULL,   -- 上次确认活跃（= 上次续期或校验通过）的时间
    EXPIRE_TIME         TIMESTAMP(6)  NOT NULL,   -- 过期边界，滑动续期时不越过 LOGIN_TIME+绝对上限

    -- 是否"记住我"：长期免登录，过期时长更长
    REMEMBER_ME         NUMBER(1) DEFAULT 0 NOT NULL CHECK (REMEMBER_ME IN (0, 1)),

    -- 逻辑状态：ACTIVE 有效 / EXPIRED 超时失效 / LOGOUT 主动登出 / KICKED 被踢下线
    STATUS              VARCHAR2(16)  NOT NULL,

    -- 结束原因，与 STATUS 一一对应但取值域更大，方便后面加类型（如 KICKED 可细分原因）
    LOGOUT_TYPE         VARCHAR2(32),
    LOGOUT_TIME         TIMESTAMP(6),   -- 置为终态的时间，与 STATUS 同步写入

    REMARK              VARCHAR2(500),  -- 踢出原因/备注，排查"我明明没踢它"的必备字段

    -- 审计字段
    CREATE_BY           VARCHAR2(64),
    CREATE_TIME         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_BY           VARCHAR2(64),
    UPDATE_TIME         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_SYS_USER_SESSION PRIMARY KEY (ID)
);

