--      ID NUMBER NOT NULL,
--    并单独建序列 + 触发器（触发器只在 ID 为空时赋值，配合 MyBatis-Plus 的 IdType.INPUT）：
--      CREATE SEQ SYS_USER_SESSION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
